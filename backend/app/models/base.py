"""Общие хелперы для моделей: PK, FK, временные метки, CHECK по StrEnum."""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Text,
    func,
    text,
)
from sqlalchemy.orm import MappedColumn, mapped_column

from app.core.db import Base

# Аннотации по умолчанию: datetime -> timestamptz, str -> text
Base.registry.update_type_annotation_map({datetime: DateTime(timezone=True), str: Text})

FALSE = text("false")
TRUE = text("true")
ZERO = text("0")
JSONB_OBJECT = text("'{}'::jsonb")
JSONB_ARRAY = text("'[]'::jsonb")
TEXT_ARRAY_EMPTY = text("'{}'::text[]")


def utcnow() -> datetime:
    """Для `onupdate=`: updated_at обновляется приложением, а не триггером."""
    return datetime.now(UTC)


def pk() -> MappedColumn[int]:
    """bigint GENERATED BY DEFAULT AS IDENTITY."""
    return mapped_column(BigInteger, Identity(always=False), primary_key=True)


def fk(
    target: str,
    *,
    nullable: bool = False,
    ondelete: str | None = None,
    use_alter: bool = False,
    primary_key: bool = False,
) -> MappedColumn[Any]:
    """bigint-ссылка на `table.column`; по умолчанию ON DELETE RESTRICT."""
    return mapped_column(
        BigInteger,
        ForeignKey(target, ondelete=ondelete, use_alter=use_alter),
        nullable=nullable,
        primary_key=primary_key,
    )


def created_at() -> MappedColumn[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


def updated_at() -> MappedColumn[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=utcnow)


def in_check(column: str, values: type[StrEnum], name: str) -> CheckConstraint:
    """CHECK (column IN (...)) со значениями из StrEnum; имя -> ck_<table>_<name>."""
    items = ", ".join(f"'{v.value}'" for v in values)
    return CheckConstraint(f"{column} IN ({items})", name=name)
