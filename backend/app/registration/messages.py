def format_registered_at(at: datetime, tz: ZoneInfo) -> str:
    """«дд.мм, чч:мм» в часовом поясе мероприятия."""
    return at.astimezone(tz).strftime("%d.%m, %H:%M")


def already_registered(at: datetime, tz: ZoneInfo) -> str:
    """DP-01: повторный скан или проигранная гонка."""
    return (
        f"Вы уже зарегистрированы ({format_registered_at(at, tz)}). "
        "Если вы не получили бейдж — обратитесь к стойке регистрации"
    )
